/* Local file QA. Review choices and downloads remain in a disposable browser context. */
const fs = require('fs'), path = require('path'), assert = require('node:assert/strict'), { pathToFileURL } = require('url')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const root = path.resolve(__dirname, '..'), report = path.join(__dirname, 'public/repricing/index.html'), evidence = path.join(root, 'delivery-tests/repricing')
fs.mkdirSync(evidence, { recursive: true })
let n = 0
const check = (name, ok) => { assert.ok(ok, name); n++; console.log('PASS ' + name) }
;(async () => {
  let browser
  try {
    browser = await chromium.launch({ headless: true, ...(process.env.CHROME_EXECUTABLE ? { executablePath: process.env.CHROME_EXECUTABLE } : {}), args: ['--no-sandbox'] })
    const context = await browser.newContext({ viewport: { width: 1600, height: 1050 }, acceptDownloads: true })
    const page = await context.newPage(), errors = [], external = []
    page.on('pageerror', e => errors.push(e.message))
    await context.route('**/*', route => {
      const url = route.request().url()
      if (!/^(file:|blob:|data:|about:)/.test(url)) { external.push(url); return route.abort() }
      return route.continue()
    })
    await page.goto(pathToFileURL(report).href)
    check('standalone file shows 38 security rows and 34 issuer details without a server', await page.locator('#checklist tbody tr').count() === 38 && await page.locator('article.company-detail').count() === 34)
    check('opening date and evidence freeze are distinct', (await page.locator('header').innerText()).includes('2026-10-25') && (await page.locator('footer').innerText()).includes('2026-10-24'))
    check('all company links resolve to a rendered issuer detail', await page.locator('#checklist td.issuer a').evaluateAll(xs => xs.every(x => document.getElementById(x.getAttribute('href').slice(1)))))
    check('readable amounts have no NaN, Infinity or missing-value artifacts', !/NaN|Infinity|undefined/.test(await page.locator('body').innerText()))
    await page.screenshot({ path: path.join(evidence, 'repricing-desktop.png'), fullPage: false })
    for (const [scope, count] of [['current', 31], ['history', 6], ['comparison', 1]]) {
      await page.locator('#scope').selectOption(scope)
      check(scope + ' scope has the exact security count', await page.locator('#checklist tbody tr:visible').count() === count)
    }
    await page.locator('#scope').selectOption(''); await page.locator('#search').fill('中国移动')
    check('issuer search includes both A and H rows', await page.locator('#checklist tbody tr:visible').count() === 2)
    await page.locator('#search').fill(''); await page.locator('#search').blur()
    await page.locator('#checklist').scrollIntoViewIfNeeded()
    await page.screenshot({ path: path.join(evidence, 'repricing-checklist.png'), fullPage: false })
    await page.locator('#search').fill('腾讯')
    await page.locator('select[data-review="0700.HK"]').selectOption('agree_research')
    await page.locator('textarea[data-note="0700.HK"]').fill('合成验收备注：先核现金预算')
    check('review updates local counter without granting execution', (await page.locator('#reviewCount').innerText()).includes('1 / 37') && await page.evaluate(() => PACK.rows.every(r => !r.executionApproved && !r.activated)))
    await page.reload()
    check('review choice and note survive a local file reload', await page.locator('select[data-review="0700.HK"]').inputValue() === 'agree_research' && (await page.locator('textarea[data-note="0700.HK"]').inputValue()).includes('合成验收'))
    await page.locator('#search').fill('分众')
    await page.locator('select[data-review="002027.SZ"]').selectOption('agree_research')
    check('agreeing with research cannot remove a C-grade buy block', (await page.locator('#checklist tbody tr:visible').innerText()).includes('暂不启用'))
    const [download] = await Promise.all([page.waitForEvent('download'), page.locator('#export').click()])
    const exported = JSON.parse(fs.readFileSync(await download.path(), 'utf8'))
    check('download contains all 37 pool decisions with the exact proposal version', exported.decisions.length === 37 && exported.proposalVersion === await page.evaluate(() => PACK.version))
    check('export preserves new tiers and downside, never turns review into approval', exported.decisions.every(d => !d.executionApproved && d.suggestions.length === 3 && d.irrAtProposedFirstPrice) && !exported.executionApproved && !exported.accountDataTouched && exported.decisions.find(d => d.code === '002027.SZ').blockers.length > 0)
    await page.locator('#search').fill(''); await page.locator('#search').blur()
    await page.locator('#detail-ninghu').scrollIntoViewIfNeeded()
    check('finite road distribution is visibly distinguished from full company valuation', (await page.locator('#detail-ninghu').innerText()).includes('十年有限分配现金下限'))
    await page.screenshot({ path: path.join(evidence, 'ninghu-finite-review.png'), fullPage: false })
    const mobileContext = await browser.newContext({ viewport: { width: 390, height: 844 } })
    const mobile = await mobileContext.newPage(); await mobile.goto(pathToFileURL(report).href)
    check('phone view keeps wide tables inside their own scroll containers', await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
    await mobile.screenshot({ path: path.join(evidence, 'repricing-mobile.png'), fullPage: false })
    await mobileContext.close()
    const blockedStorage = await browser.newContext()
    await blockedStorage.addInitScript(() => { Storage.prototype.setItem = function () { throw Error('storage disabled for QA') } })
    const p = await blockedStorage.newPage(); await p.goto(pathToFileURL(report).href)
    await p.locator('select[data-review="0700.HK"]').selectOption('watch')
    check('disabled local storage is reported honestly and export remains available', (await p.locator('#savedState').innerText()).includes('内存') && await p.locator('#export').isEnabled())
    await blockedStorage.close()
    check('report has no runtime errors and makes no remote/account requests', errors.length === 0 && external.length === 0)
    console.log('Repricing browser acceptance: ' + n + ' checks passed; local standalone file and disposable review data only.')
  } finally { if (browser) await browser.close() }
})().catch(e => { console.error(e); process.exitCode = 1 })
