def price_for_r(eps,pay,g,exitpe,r,tax,n=10):
    e=eps; pv=0.0
    for t in range(1,n+1):
        e*=(1+g); pv+=e*pay*(1-tax)/(1+r)**t
    return pv+e*exitpe/(1+r)**n
def irr_now(price,eps,pay,g,exitpe,tax,n=10):
    lo,hi=-0.5,1.0
    for _ in range(200):
        m=(lo+hi)/2
        if price_for_r(eps,pay,g,exitpe,m,tax)>price: lo=m
        else: hi=m
    return (lo+hi)/2
